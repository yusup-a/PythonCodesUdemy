# + adding
print(2+3)

# - subtracting
print(5-4)

# * multiplication
print(3*5)

# / standard division
print(7/2) #ALWAYS produces a float number, even when you divide 2 integers

# // integer division
# Int division always returns the nearest whole number rounded DOWN
# so it cuts off all the decimals
print(6//2)
print(7//2)

# % modulus division
#  This returns the remainder of the division
print(6%2)
print(7%2)

#CAN NOT divide by 0 using ANY of the division operators

# ^ power operator
print(2**3) #which equals 2^3 = 2*2*2 = 8

# when you use 2 integers with an operator, you can an integer
# when you use 1 integer and 1 float with an operator, you can a float
# when you use 2 floats with an operator, you can a float